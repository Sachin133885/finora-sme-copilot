import assert from 'node:assert/strict';
import {parseReceiptText,validateReceipt,postReceipt} from '../src/pdf-receipts.js';
import {seed,summary} from '../src/engine.js';
const text='FINORA RECEIPT V1\nReceipt ID: TEST-1\nTransaction Date: 2026-10-12\nBusiness ID: shenzhen\nDirection: INCOME\nCounterparty: Jade Market\nCategory: sales\nDescription: Project payment\nPayment Method: bank\nCurrency: CNY\nSubtotal: 1000.00\nTax Amount: 0.00\nTotal: 1000.00\nInvoice Reference: INV-1042\nPayment Status: PAID';
const d=seed('shenzhen'),r=parseReceiptText(text);
assert.equal(validateReceipt(r,d).total,100000);
assert.throws(()=>postReceipt(d,r,{confirmed:false,paid:true,role:'owner'}),/confirmation/);
assert.throws(()=>postReceipt(d,r,{confirmed:true,paid:false,role:'owner'}),/payment/);
assert.throws(()=>postReceipt(d,r,{confirmed:true,paid:true,role:'viewer'}),/read.only/);
assert.throws(()=>validateReceipt({...r,businessId:'chengdu'},d),/business/);
assert.throws(()=>validateReceipt({...r,total:'1002.00'},d),/total/);
assert.throws(()=>validateReceipt({...r,currency:'USD'},d),/currency/);
assert.throws(()=>validateReceipt({...r,date:'2026-02-30'},d),/date/);
assert.throws(()=>validateReceipt({...r,party:''},d),/party/);
const n=postReceipt(d,r,{confirmed:true,paid:true,role:'accountant'});
assert.equal(summary(n).cash-summary(d).cash,100000);
assert.equal(n.invoices.find(i=>i.id==='INV-1042').paid,100000);
assert.throws(()=>postReceipt(n,r,{confirmed:true,paid:true,role:'owner'}),/duplicate/);
assert.throws(()=>validateReceipt({...r,receiptId:'OTHER'},n),/duplicate/);
assert.equal(d.invoices[0].paid,0);
console.log('PDF validation, confirmation, role, isolation, settlement and duplicate tests passed');
